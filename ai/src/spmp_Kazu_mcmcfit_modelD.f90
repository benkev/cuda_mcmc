!-----------------------------------------------------------------------
! SUBROUTINE mcmcfit
! 
! This subroutine does replica exchange MCMC simulations
!
! Writer  : Kazunori Akiyama
! Version : 20120721
! 
! dependency
!   module  : modeld (modelD.f90)
!   modele  : mtmod  (mt19937.f90)
!-----------------------------------------------------------------------
subroutine mcmcfit (CSu,CSv,CSamp,CSamp_err,&
                    BSu1,BSv1,BSu2,BSv2,BSu3,BSv3,BSphase,BSphase_err,&
                    pmin,pmax,&
                    niter,nburn,nadj,&
                    nbeta,beta1,betaN,&
                    pout,tout,chisqout,&
                    rate_acpt,rate_exch,&
                    CSnum,BSnum,pnum)
    ! import modules
    !$use omp_lib
    use modeld      ! Visibility Models
    use mtmod       ! random number generator based on MT method
    
    implicit none
    
    ! common variables related with parallel programing
    !   the total number of processors
    integer,parameter   :: psnum = 8
    !   indicates ID of each processor
    integer             :: ps
    
    ! arguments relating with replica-exchange MCMC algorism!
    integer,    intent(in) :: nbeta ! the number of temperatures
    real(8),    intent(in) :: beta1 ! the first temperture
    real(8),    intent(in) :: betaN ! the last temperature
    
    ! arguments (input) !
    !   niter : iteration number
    !   nburn : iteration number for burn-in
    !   nadj  : number of sets for calcurating rates of "accept"
    !           when step sizes are adjusted in burn-in.
    integer,    intent(in)  :: niter,nburn,nadj
    !   number of Cross power spectrums and bi-spctrums
    integer,    intent(in)  :: CSnum,BSnum
    !   Cross power spctrums:: UV, Amplitudes, errors of amplitude
    real(8),    intent(in)  :: CSu(1:CSnum),CSv(1:CSnum),&
                               CSamp(1:CSnum),CSamp_err(1:CSnum)
    !   Bi-spectrum: UV, Phases, errors of phases
    real(8),    intent(in)  :: BSu1(1:BSnum),BSv1(1:BSnum),&
                               BSu2(1:BSnum),BSv2(1:BSnum),&
                               BSu3(1:BSnum),BSv3(1:BSnum),&
                               BSphase(1:BSnum),BSphase_err(1:BSnum)
    !   number of parameters
    integer,    intent(in)  :: pnum
    !   boundary conditions of parameters
    real(8),    intent(in)  :: pmin (1:pnum),pmax(1:pnum)
    
    ! arguments (output) !
    !   sets of parameters generated by MCMC
    real(8),    intent(out) :: pout(1:pnum,1:nbeta,1:niter*psnum)
    !   temperature histories of each chain
    integer,    intent(out) :: tout(1:nbeta,1:niter*psnum)
    !   chisquares of each set of parameters
    real(8),    intent(out) :: chisqout(1:niter*psnum)
    !   accept rate/exchange rate
    real(8),    intent(out) :: rate_acpt(1:pnum,1:nbeta)
    real(8),    intent(out) :: rate_exch(1:nbeta)
    
    ! common variables related with MCMC algorisms!
    !   variances of Visibility amplitudes
    real(8) :: CSamp_var(1:CSnum)
    !   variances of closure phases
    real(8) :: BSphase_var(1:BSnum)
    !   Temperatures
    real(8) :: beta (1:nbeta)
    !   conting numbers of accepted proposal sets in the M-H algorism
    integer :: n_acpt(1:pnum,1:nbeta,1:psnum)
    !   conting numbers of exchanged adjant chanins in the replica exchange algorism
    integer :: n_exch(1:nbeta,1:psnum)
    
    ! calculate variances !
    CSamp_var   = CSamp_err**2
    BSphase_var = BSphase_err**2
    
    ! initialize !
    call init_randoms()
    
    ! initialize beta !
    call init_beta()
    
    ! do MCMC
    !$OMP PARALLEL DO
    do ps=1,psnum
        call main_loop(pout(1:pnum,1:nbeta,niter*(ps-1)+1:niter*ps),&
                       tout(1:nbeta,       niter*(ps-1)+1:niter*ps),&
                       chisqout(niter*(ps-1)+1:niter*ps),&
                       n_acpt(1:pnum,1:nbeta,ps),&
                       n_exch(1:nbeta,ps))
    end do
    !$OMP END PARALLEL DO
    
    ! calcurate accept/exchange rate
    !   initialize
    rate_acpt(1:pnum,1:nbeta) = 0
    rate_exch(1:nbeta)        = 0
    !   calcurate sums of "accept"/"exchange" conter of each process
    do ps=1,psnum
        rate_acpt(1:pnum,1:nbeta) = rate_acpt(1:pnum,1:nbeta) + n_acpt(1:pnum,1:nbeta,ps)
        rate_exch(1:nbeta)        = rate_exch(1:nbeta)        + n_exch(1:nbeta,ps)
    end do
    !   calcurate rates
    rate_acpt(1:pnum,1:nbeta) = rate_acpt(1:pnum,1:nbeta) /niter/psnum
    rate_exch(1:nbeta)        = rate_exch(1:nbeta)        /niter/psnum
    
contains
    subroutine main_loop(pout,tout,chisqout,n_acpt,n_exch)
        implicit none
        ! arguments (out)
        !   sets of prameters/temperature histories/chisquares
        real(8), intent(out) :: pout(1:pnum,1:nbeta,1:niter)
        integer, intent(out) :: tout(1:nbeta,1:niter)
        real(8), intent(out) :: chisqout(1:niter)
        !   conting number of accepted proposal sets in M-H algorism
        integer, intent(out) :: n_acpt(1:pnum,1:nbeta)
        integer, intent(out) :: n_exch(1:nbeta)
        
        ! Local Variables
        !   step size
        real(8) :: pstp (1:pnum,1:nbeta)
        !   current parameters
        real(8) :: pcur (1:pnum,1:nbeta)
        !   current tempertures as a function of initial tempertures
        integer :: tcur (1:nbeta)
        !   current chisquare
        real(8) :: chisq(1:nbeta)
        !   memorize history of "accept"/"reject" in current nadj trials
        integer :: n_hist(1:nadj,1:pnum,1:nbeta)
        !   counting number of Metropolice trials
        integer :: n_cnt (1:pnum,1:nbeta)
        !   intgers for loops
        integer :: i,j,k,n,m,l
        
        ! Initialize parameters
        do j = 1, pnum
            pcur(j,1:nbeta)  = (pmax(j)-pmin(j)) * grnd() + pmin(j)
        end do
        
        ! Initialize steps
        do i = 1, nbeta
             pstp(1:pnum,i) = (pmax(1:pnum)-pmin(1:pnum))/50.0d0
        end do
        
        ! Initialize counters
        n_acpt(1:pnum,1:nbeta) = 0
        n_exch(1:nbeta) = 0
        n_hist(1:nadj,1:pnum,1:nbeta) = 0
        n_cnt (1:pnum,1:nbeta) = 1
        
        ! Initialize chi-square
        do i = 1, nbeta
            call calc_chisq  (CSu,CSv,CSamp,CSamp_var,BSu1,BSv1,BSu2,BSv2,BSu3,BSv3,BSphase,BSphase_var,&
                              pcur(1:pnum,i),chisq(i),CSnum,BSnum)
        end do
        
        ! initialize tcur
        do i = 1, nbeta
            tcur (i) = i
        end do
        
        ! initialize pout,tout
        pout(1:pnum,1:nbeta,1:niter) = 0.0d0
        tout(1:pnum,1:niter)         = 0.0d0
        
        ! BURN IN
        do n = 1, nburn
            ! generate n-th sets of parameters
            call reMCMC_burnin (n,tcur,pcur,chisq,pstp,n_hist,n_cnt)
        end do
        
        ! MAIN LOOP
        do n = 1, niter
            ! generate n-th sets of parameters
            call reMCMC_main (n,tcur,pcur,chisq,pstp,n_acpt,n_exch)
            
            ! memorize current parameters, temperatures of all chanins
            ! and a chisquare at beta=1
            pout(1:pnum,1:nbeta,n) = pcur(1:pnum,1:nbeta)
            tout(1:nbeta,n)        = tcur(1:nbeta)
            chisqout(n)            = chisq(1)
        end do
    end subroutine main_loop
    
    subroutine reMCMC_burnin(n,tcur,pcur,chisq,pstp,n_hist,n_cnt)
        ! arguments (in)
        integer, intent(in)     :: n    ! means n-th iteration
        integer, intent(inout)  :: tcur (1:nbeta)
        
        ! arguments (inout)
        !   step size (adjusted in burn-in period)
        real(8), intent(inout)  :: pstp (1:pnum,1:nbeta)
        !   current parameters/chisquare
        real(8), intent(inout)  :: pcur (1:pnum,1:nbeta)
        real(8), intent(inout)  :: chisq(1:nbeta)
        !   conting numbers of "accept" of proposal set in M-H algorithm
        integer, intent(inout)  :: n_hist(1:nadj,1:pnum,1:nbeta)
        !   conting numbers of trials
        integer, intent(inout)  :: n_cnt (1:pnum,1:nbeta)
        
        ! local variables !
        !   variables used for replica-exchanges
        real(8) :: u,r,alpha
        !   accept rate
        real(8) :: rate
        !   dammy values
        real(8)  :: pdam(1:pnum),dammy
        !   dammy values
        integer  :: dammy_int
        !   mod ( number of trials, nadj)
        integer  :: modn
        !   integers for loop
        integer  :: i,j,k
        !   memorize status of the latest mcmc step
        !       1: accepted / else: rejected
        integer  :: flag_acpt
        
        ! update parameters using M-H MCMC algorisms
        ! loop for tempertures
        do i = 1, nbeta
            ! loop for parameters
            do j = 1, pnum
                ! Randomely select k-th parameter for updating
                k = int( pnum * grnd() ) + 1
                
                ! updating k-th parameters of a chian at i-th temperature
                call spmpMCMC(k,beta(i),pcur(1:pnum,i),chisq(i),pstp(1:pnum,i),&
                              flag_acpt)
                
                ! adjusting stepsize
                !   calcrate modn
                modn = mod(n_cnt (k,i),nadj) + 1
                !   memorize history of accept/reject
                if (flag_acpt == 1) then
                    n_hist (modn,k,i) = 1   !accept
                else
                    n_hist (modn,k,i) = 0   !reject
                end if
                !   calcurate accept rate of latest nadj trials
                rate = real(sum(n_hist(1:nadj,k,i)))/ minval( (/ nadj, n_cnt (k,i) /) )
                !   adjust a step size
                if (rate < 0.30) then
                    pstp(k,i) = pstp(k,i) / 1.01
                else if (rate > 0.20) then
                    pstp(k,i) = pstp(k,i) * 1.01
                end if
                
                n_cnt (k,i) = n_cnt (k,i) + 1
            end do
        end do
        
        ! do replica-exchange
        do i = 1, nbeta-1
            ! Randomely select adjacent chains
            k = int( (nbeta-1) * grnd() ) + 1
            
            ! calcurate metropolice ratio in selected adjacent chains
            r = exp ( - 0.5d0 * (beta(k+1) - beta(k)) * (chisq(k) - chisq(k+1)))
            
            ! calcurate probability for acceptance
            alpha = minval((/ r, 1d0 /))
            
            ! exchange adjant chains with a probability alpha
            u = grnd()
            if (u <= alpha) then
                ! exchange tempertures
                dammy_int = tcur(k)
                tcur(k)   = tcur(k+1)
                tcur(k+1) = dammy_int
                
                ! exchange parameters
                pdam(1:pnum)     = pcur(1:pnum,k)
                pcur(1:pnum,k)   = pcur(1:pnum,k+1)
                pcur(1:pnum,k+1) = pdam(1:pnum)
                
                ! exchange chisquares
                dammy      = chisq(k)
                chisq(k)   = chisq(k+1)
                chisq(k+1) = dammy
            end if
        end do
    end subroutine reMCMC_burnin
    
    subroutine reMCMC_main(n,tcur,pcur,chisq,pstp,n_acpt,n_exch)
        ! arguments (in)
        integer, intent(in)     :: n    ! means n-th iteration
        integer, intent(inout)  :: tcur (1:nbeta)
        
        ! arguments (inout)
        !   step size (adjusted in burn-in period)
        real(8), intent(inout)  :: pstp (1:pnum,1:nbeta)
        !   current parameters/chisquare
        real(8), intent(inout)  :: pcur (1:pnum,1:nbeta)
        real(8), intent(inout)  :: chisq(1:nbeta)
        !   conting numbers of accepted proposal sets in the M-H algorism
        integer :: n_acpt(1:pnum,1:nbeta)
        !   conting numbers of exchanged adjant chanins in the replica exchange algorism
        integer :: n_exch(1:nbeta)
        
        ! local variables !
        !   variables used for replica-exchanges
        real(8) :: u,r,alpha
        !   dammy values
        real(8)  :: pdam(1:pnum),dammy
        !   dammy values
        integer  :: dammy_int
        !   mod ( number of trials, nadj)
        integer  :: modn
        !   integers for loop
        integer  :: i,j,k
        !   memorize status of the latest mcmc step
        !       1: accepted / 0: rejected
        integer  :: flag_acpt
        
        ! loop for tempertures
        do i = 1, nbeta
            ! loop for parameters
            do j = 1, pnum
                ! Randomely select k-th parameter for updating
                k = int( pnum * grnd() ) + 1
                
                ! updating k-th parameters of a chian at i-th temperature
                call spmpMCMC(k,beta(i),pcur(1:pnum,i),chisq(i),pstp(1:pnum,i),flag_acpt)
                
                n_acpt(k,i) = n_acpt(k,i) + flag_acpt
            end do
        end do
        
        ! do replica-exchange
        do i = 1, nbeta-1
            ! Randomely select adjacent chains
            k = int( (nbeta-1) * grnd() ) + 1
            
            ! calcurate metropolice ratio in selected adjacent chains
            r = exp ( - 0.5d0 * (beta(k+1) - beta(k)) * (chisq(k) - chisq(k+1)))
            
            ! calcurate probability for acceptance
            alpha = minval((/ r, 1d0 /))
            
            ! exchange adjant chains with a probability alpha
            u = grnd()
            if (u <= alpha) then
                ! exchange tempertures
                dammy_int = tcur(k)
                tcur(k)   = tcur(k+1)
                tcur(k+1) = dammy_int
                
                ! exchange parameters
                pdam(1:pnum)     = pcur(1:pnum,k)
                pcur(1:pnum,k)   = pcur(1:pnum,k+1)
                pcur(1:pnum,k+1) = pdam(1:pnum)
                
                ! exchange chisquares
                dammy      = chisq(k)
                chisq(k)   = chisq(k+1)
                chisq(k+1) = dammy
                
                n_exch(k)  = n_exch(k) + 1
            end if
        end do
    end subroutine reMCMC_main
    
    ! Subroutine for Single Parameter Metropolice MCMC
    subroutine spmpMCMC(i,beta,pcur,chisq,pstp,flag_acpt)
        ! arguments (in)
        !   parameter ID (means i-th parameter)
        integer,    intent(in)      :: i
        !   temperture
        real(8),    intent(in)      :: beta
        
        ! arguments (inout)
        !   current parameters/chisquare
        real(8),    intent(inout)   :: pcur(1:pnum)
        real(8),    intent(inout)   :: chisq
        !   step sizes
        real(8),    intent(inout)   :: pstp(1:pnum)
        
        ! arguments (out)
        !   status of this tral (1:accepted/0:rejected)
        integer,    intent(out)     :: flag_acpt
        
        ! local variable !
        !   proposed parameters
        real(8) :: pnew(1:pnum)
        !   chisquare of proposed parameters
        real(8) :: chisq_new
        !   variables for the M-H algorithm
        real(8) :: u,alpha
        !   dammy variable
        real(8) :: dammy(1:1)
        !   memorize status of proposed parameters
        !       1  : inside boundary conditions
        !       -1 : outside boundary conditions
        integer :: flag
        
        ! step i-th parameter !
        pnew = pcur
        call random_gauss(pcur(i),pstp(i),dammy,1)
        pnew(i) = dammy(1)
        
        ! check whether proposed parameters are inside of boundary conditions
        call check_p (pmin,pmax,pnew,flag)
        
        ! calcurate chisquares and probability for accepting the proposed set
        if (flag < 0) then
            ! if proposed parameters are outside of boundary conditions,
            ! they are rejected.
            alpha=0
        else
            ! calcurate chisquare
            call calc_chisq  (CSu,CSv,CSamp,CSamp_var,BSu1,BSv1,BSu2,BSv2,BSu3,BSv3,BSphase,BSphase_var,&
                              pnew,chisq_new,CSnum,BSnum)
            ! calcurate probability for accepting the proposed set
            alpha = minval((/ exp(- 0.5d0 * beta * (chisq_new - chisq)), 1d0 /))
        end if
        
        ! accepting the proposal set with a probability alpha
        u = grnd()
        if (u <= alpha) then
            ! accepting the proposal set
            pcur      = pnew
            chisq     = chisq_new
            flag_acpt = 1
        else
            flag_acpt = 0
        end if
    end subroutine spmpMCMC
    
    ! Subroutines for initializing beta
    subroutine init_beta()
        implicit none
        integer :: i
        real(8) :: step
        
        step = (betaN/beta1)**(1.0d0/(nbeta-1))
        
        do i=1,nbeta
            beta(i) = beta1 * (step) ** (i-1)
        end do
        !beta = beta / sum(beta)
    end subroutine init_beta
    
    ! Subroutine for initializing random numbers !
    ! initialize seeds for random numbers generated by MT method
    subroutine init_randoms()
        implicit none
        integer :: seed
        ! init seed
        call system_clock(count = seed)
        call sgrnd(seed)    
    end subroutine init_randoms
    
    ! Subroutine for creating random gaussian with Box-Muller transform
    ! input  mu: mean of Gaussian, sigma : deviation of Gaussian
    ! output x: random number which follows gaussian probability dist.
    subroutine random_gauss(mu,sigma,x,n)
        implicit none
        integer,    intent(in)    :: n
        real(8),    intent(in)    :: mu   (1:n)
        real(8),    intent(in)    :: sigma(1:n)
        real(8),    intent(out)   :: x    (1:n)
        
        real(8) :: x0(1:n), y0(1:n)
        real(8) :: pi
        integer :: i
        
        pi = atan(1.0d0)*4.0d0
        do i = 1, n
            x0(i) = grnd()
            y0(i) = grnd()
        end do
        x  = sqrt(-2.0d0*log(x0))*sin(2.0d0*pi*y0)
        x  = x*sigma + mu
    end subroutine random_gauss
end subroutine mcmcfit
